"""
famous_quote.py - String Quotes and Variable Concatenation

This script demonstrates working with text strings in Python:
- Handling nested quotes (combining single and double quotes)
- Assigning strings to variables
- Combining string variables using string concatenation
"""

famous_quote = 'Albert Camus once said "One must imagine Sisyphus Happy."'
print(famous_quote)

famous_person = 'Albert Camus'
message = famous_person + " " + 'once said "One must imagine Sisyphus Happy."'
print(message)

