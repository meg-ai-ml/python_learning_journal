#This short program is for creating a tuple.

buffet = ("bread", "butter", "jam", "cereal", "milk" )

#Printing the tuple's output using index method.

print(buffet[0]) #bread
print(buffet[1]) #butter
print(buffet[2]) #jam
print(buffet[3]) #cereal
print(buffet[4]) #milk

#Printing the tuple's output using for loop.

for food in buffet:
    print(food)
    
