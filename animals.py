#This short program is to name three animals and why it would be a great pet using for loop.

# Using the list function, we store the name of three animals by declaring the animals variable.

animals = [ "cats", "dogs", "bunnies"]

#Using for loop in order to name an animal and that it would make a great pet.

for animal in animals:
    print(animal)
    print("A " + animal + " would make a great pet")

#Using print function, to state that all of these animals would make great pets.
    
print("All of these animals would make great pets.")


